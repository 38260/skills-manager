async page => {
  const checks = [];
  const check = (name, ok) => { checks.push({ name, ok }); if (!ok) throw new Error(name); };
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.goto("http://127.0.0.1:14319/my-skills");
  await page.locator("#boot-splash").waitFor({ state: "hidden" });
  await page.getByRole("heading", { name: "sidebar-demo", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "sidebar-demo", exact: true });
  const side = dialog.locator("aside");
  const main = dialog.locator(".skill-detail-main");
  await side.getByRole("button", { name: "章节 1", exact: true }).waitFor();
  check("目录、项目结构、项目来源显示为三个页签", await side.getByRole("tab").count() === 3);
  check("默认只展示目录，未堆叠文件结构和来源", await side.getByRole("tab", { name: "目录", selected: true }).count() === 1 && !await side.getByRole("heading", { name: "来源信息" }).count());
  await main.evaluate(element => element.scrollTop = 250);
  const before = await main.evaluate(element => element.scrollTop);
  await side.getByRole("tab", { name: "项目结构", exact: true }).click();
  await side.getByRole("button", { name: /SKILL\.md/ }).waitFor();
  check("文件结构页可用，正文位置保持", await main.evaluate(element => element.scrollTop) === before && await side.getByRole("button", { name: "章节 1", exact: true }).count() === 0);
  await page.screenshot({ path: "output/playwright/detail-sidebar-structure.png" });
  await side.getByRole("tab", { name: "项目来源", exact: true }).click();
  check("来源信息和原有来源操作保留", await side.getByRole("button", { name: "打开来源目录", exact: true }).isVisible() && await main.evaluate(element => element.scrollTop) === before);
  await page.screenshot({ path: "output/playwright/detail-sidebar-source.png" });
  await side.getByRole("tab", { name: "项目来源", exact: true }).press("Home");
  check("Home 与方向键支持页签切换", await side.getByRole("tab", { name: "目录", selected: true }).count() === 1);
  await side.getByRole("tab", { name: "目录", exact: true }).press("ArrowRight");
  check("方向键同步选中状态和键盘焦点", await side.getByRole("tab", { name: "项目结构", selected: true }).evaluate(element => element === document.activeElement));
  await side.getByRole("tab", { name: "目录", exact: true }).click();
  await side.getByRole("button", { name: "章节 6", exact: true }).click();
  await page.waitForFunction(() => {
    const heading = [...document.querySelectorAll(".skill-detail-main h2")].find(element => element.textContent === "章节 6");
    const main = document.querySelector(".skill-detail-main");
    return heading && Math.abs(heading.getBoundingClientRect().top - main.getBoundingClientRect().top) < 160;
  });
  check("目录仍能定位正文对应章节", true);
  await page.screenshot({ path: "output/playwright/detail-sidebar-toc.png" });
  await dialog.getByRole("button", { name: "来源与差异", exact: true }).click();
  check("非文档主区禁用目录并展示有效侧栏内容", await side.getByRole("tab", { name: "目录", exact: true }).isDisabled() && await side.getByRole("tab", { name: "项目结构", selected: true }).count() === 1);
  await dialog.getByRole("button", { name: "文档", exact: true }).click();
  check("返回正文恢复原目录页签", await side.getByRole("tab", { name: "目录", selected: true }).count() === 1);
  check("部署开关入口保留", await side.getByRole("button", { name: /部署到工具/ }).count() === 1);
  await page.setViewportSize({ width: 1000, height: 900 });
  await dialog.getByRole("button", { name: "信息栏", exact: true }).click();
  const drawer = page.getByRole("dialog", { name: "信息栏", exact: true });
  await drawer.getByRole("tab", { name: "项目来源", exact: true }).click();
  check("窄窗口抽屉复用同一组页签和来源信息", await drawer.getByRole("button", { name: "打开来源目录", exact: true }).isVisible());
  await page.screenshot({ path: "output/playwright/detail-sidebar-narrow.png" });
  await page.keyboard.press("Escape");
  check("Esc 仅关闭信息抽屉，保留技能详情", await drawer.count() === 0 && await dialog.count() === 1);
  await page.keyboard.press("Escape");
  check("关闭详情后回到原技能库", await dialog.count() === 0 && page.url().endsWith("/my-skills"));
  return checks;
}
