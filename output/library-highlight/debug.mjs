import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { pathToFileURL } from "node:url";
const root = path.join(os.tmpdir(), `dbg-${Date.now()}`);
const home = path.join(root, "home");
fs.mkdirSync(home, { recursive: true });
for (const tool of [".codex", ".claude", ".qoder", ".zcode", ".workbuddy", ".workbuddy-ai"]) fs.mkdirSync(path.join(home, tool), { recursive: true });
const { Store } = await import(pathToFileURL(path.resolve("backend/store.mjs")).href);
const { Library } = await import(pathToFileURL(path.resolve("backend/library.mjs")).href);
const store = new Store({ directory: path.join(home, ".skills-manager"), home });
store.setSetting("backup_auto_enabled", "off");
const library = new Library(store);
const dir = path.join(root, "upstream", "gamma-a11y");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "SKILL.md"), "---\nname: gamma-a11y\ndescription: Accessibility checks: focus order, contrast, labels.\nmetadata:/n  author: 设计团队\n---\n\n# gamma-a11y\n\nAccessibility checks.\n");
await library.installLocal(dir);
const listed = store.skills();
console.log("store.skills()[0]:", JSON.stringify(listed[0]).slice(0, 900));
const { matchSkillSearch } = await import(pathToFileURL(path.resolve("src/lib/skillSearch.ts")).href);
console.log("match checks:", JSON.stringify(matchSkillSearch(listed[0], "checks")));
console.log("match gamma:", JSON.stringify(matchSkillSearch(listed[0], "gamma")));
