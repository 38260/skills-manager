async (page) => {
  const checks = [];
  const errors = [];
  const onError = error => errors.push(error.message);
  page.on('pageerror', onError);
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const wait = async condition => {
    const deadline = Date.now() + 8000;
    while (!await condition()) {
      if (Date.now() > deadline) throw new Error('Timed out waiting for UI state');
      await page.waitForTimeout(50);
    }
  };
  const dialog = () => page.getByRole('dialog', { name: 'bilingual-demo', exact: true });
  const toc = () => dialog().getByRole('navigation', { name: '目录', exact: true });
  const main = () => dialog().getByRole('main');
  const invoke = async (command, args) => {
    const response = await page.request.post(`http://127.0.0.1:14378/api/invoke/${command}`, { headers: { 'x-skills-manager-client': 'webview' }, data: args });
    const payload = await response.json();
    if (!payload.ok) throw new Error(payload.message);
    return payload.data;
  };
  await page.setViewportSize({ width: 1600, height: 1000 });
  await wait(async () => await dialog().getByRole('button', { name: '中文版', exact: true }).getAttribute('aria-pressed') === 'true');
  assert((await main().innerText()).includes('提交前审查改动'), 'Default Chinese content');
  assert((await toc().innerText()).includes('什么时候使用'), 'Chinese TOC');
  checks.push('有译文时默认中文，目录也为中文');
  await page.screenshot({ path: 'output/playwright/bilingual-chinese.png', fullPage: true });
  await toc().getByRole('button', { name: '审查重点', exact: true }).click();
  await wait(async () => await main().evaluate(el => el.scrollTop) > 200);
  checks.push('中文目录点击能滚动定位正文');
  await dialog().getByRole('button', { name: '英文原文', exact: true }).click();
  await wait(async () => (await toc().innerText()).includes('When to use'));
  assert(!(await toc().innerText()).includes('什么时候使用'), 'Old Chinese TOC removed');
  assert((await main().innerText()).includes('Review proposed changes'), 'English original shown');
  assert(!(await main().innerText()).includes('提交前审查改动'), 'Chinese content removed');
  assert(await main().evaluate(el => el.scrollTop) < 3, 'Language switch resets scroll');
  checks.push('切换英文同时更新正文与目录并回到顶部');
  await page.screenshot({ path: 'output/playwright/bilingual-english.png', fullPage: true });
  await toc().getByRole('button', { name: 'Review checklist', exact: true }).click();
  await wait(async () => await main().evaluate(el => el.scrollTop) > 200);
  checks.push('英文目录点击能滚动定位正文');
  await dialog().getByRole('button', { name: '中文版', exact: true }).focus();
  await page.keyboard.press('Enter');
  await wait(async () => (await toc().innerText()).includes('什么时候使用'));
  assert((await main().innerText()).includes('const original = true;'), 'Code block preserved');
  checks.push('键盘可切回中文，代码块保持原样');
  await dialog().getByRole('button', { name: '调用记录', exact: true }).click();
  await dialog().getByRole('button', { name: '文档', exact: true }).click();
  await wait(async () => await dialog().getByRole('button', { name: '中文版', exact: true }).getAttribute('aria-pressed') === 'true');
  checks.push('主内容页签往返保留语言');
  await dialog().getByRole('button', { name: '英文原文', exact: true }).click();
  await dialog().getByRole('button', { name: '返回技能库', exact: true }).click();
  await page.getByRole('heading', { name: 'bilingual-demo', exact: true }).click();
  await wait(async () => await dialog().getByRole('button', { name: '中文版', exact: true }).getAttribute('aria-pressed') === 'true');
  checks.push('关闭后重新打开默认中文');
  await page.setViewportSize({ width: 900, height: 800 });
  await dialog().getByRole('button', { name: '信息栏', exact: true }).click();
  const drawer = page.getByRole('dialog', { name: '信息栏', exact: true });
  assert((await drawer.innerText()).includes('什么时候使用'), 'Narrow Chinese TOC');
  await page.screenshot({ path: 'output/playwright/bilingual-narrow.png', fullPage: true });
  await page.keyboard.press('Escape');
  assert(await drawer.count() === 0, 'Drawer closed');
  assert(await dialog().count() === 1, 'Parent remains open');
  await dialog().getByRole('button', { name: '英文原文', exact: true }).click();
  await dialog().getByRole('button', { name: '信息栏', exact: true }).click();
  assert((await drawer.innerText()).includes('When to use'), 'Narrow English TOC');
  await page.keyboard.press('Escape');
  checks.push('窄屏抽屉目录跟随语言，Esc 只关闭抽屉');
  await page.setViewportSize({ width: 1600, height: 1000 });
  await dialog().getByRole('button', { name: '返回技能库', exact: true }).click();
  await page.getByRole('heading', { name: 'english-only', exact: true }).click();
  const englishOnly = page.getByRole('dialog', { name: 'english-only', exact: true });
  await wait(async () => await englishOnly.getByRole('button', { name: '添加中文版', exact: true }).isEnabled());
  assert(await englishOnly.getByRole('button', { name: '英文原文', exact: true }).getAttribute('aria-pressed') === 'true', 'Missing translation selects English');
  assert(await englishOnly.getByRole('button', { name: '中文版', exact: true }).isDisabled(), 'Missing Chinese disabled');
  assert((await englishOnly.getByRole('main').innerText()).includes('Review proposed changes'), 'Original visible when missing');
  checks.push('无中文版默认已有原文，中文入口不可选');
  await page.screenshot({ path: 'output/playwright/bilingual-missing.png', fullPage: true });
  await englishOnly.getByRole('button', { name: '添加中文版', exact: true }).click();
  const draft = '# 新增中文\n\n## 导入验收\n这份译文只用于隔离验收。\n\n```js\nconst original = true;\n```';
  await englishOnly.getByRole('textbox', { name: '中文 Markdown 内容', exact: true }).fill(draft);
  const failSave = route => route.fulfill({ json: { ok: false, message: '验收模拟：保存失败' } });
  await page.route('**/api/invoke/set_skill_translation', failSave);
  await englishOnly.getByRole('button', { name: '保存中文版', exact: true }).click();
  await englishOnly.getByText('验收模拟：保存失败', { exact: true }).waitFor();
  assert(await englishOnly.getByRole('textbox', { name: '中文 Markdown 内容', exact: true }).inputValue() === draft, 'Failed save preserves input');
  await page.unroute('**/api/invoke/set_skill_translation', failSave);
  checks.push('保存失败保留完整输入');
  await englishOnly.getByRole('button', { name: '保存中文版', exact: true }).click();
  await englishOnly.getByText('中文版已保存', { exact: true }).waitFor();
  assert(await englishOnly.getByRole('button', { name: '中文版', exact: true }).getAttribute('aria-pressed') === 'true', 'Save selects Chinese');
  assert((await englishOnly.getByRole('navigation', { name: '目录', exact: true }).innerText()).includes('导入验收'), 'Save updates TOC');
  checks.push('粘贴译文真实保存成功，立即更新中文正文与目录');
  await englishOnly.getByRole('button', { name: '返回技能库', exact: true }).click();
  await page.reload();
  await page.getByRole('heading', { name: 'english-only', exact: true }).click();
  await wait(async () => (await englishOnly.getByRole('main').innerText()).includes('这份译文只用于隔离验收'));
  assert(await englishOnly.getByRole('button', { name: '中文版', exact: true }).getAttribute('aria-pressed') === 'true', 'Saved translation survives reload');
  checks.push('整页刷新后译文仍存在且默认中文');
  await englishOnly.getByRole('button', { name: '返回技能库', exact: true }).click();
  const failRead = route => route.fulfill({ json: { ok: false, message: '验收模拟：读取失败' } });
  await page.route('**/api/invoke/get_skill_translation', failRead);
  await page.getByRole('heading', { name: 'bilingual-demo', exact: true }).click();
  await dialog().getByText('验收模拟：读取失败', { exact: true }).waitFor();
  assert((await main().innerText()).includes('Review proposed changes'), 'Read failure preserves original');
  assert((await toc().innerText()).includes('When to use'), 'Read failure original TOC');
  await page.unroute('**/api/invoke/get_skill_translation', failRead);
  await dialog().getByRole('button', { name: '重新读取中文版', exact: true }).click();
  await wait(async () => await dialog().getByRole('button', { name: '中文版', exact: true }).getAttribute('aria-pressed') === 'true');
  checks.push('译文读取失败保留原文与目录，重试恢复中文');
  const skills = await invoke('get_managed_skills', {});
  const skill = skills.find(item => item.name === 'bilingual-demo');
  const current = await invoke('get_skill_translation', { skillId: skill.id });
  const staleRead = route => route.fulfill({ json: { ok: true, data: { ...current, stale: true } } });
  await page.route('**/api/invoke/get_skill_translation', staleRead);
  await dialog().getByRole('button', { name: '重新读取中文版', exact: true }).click();
  await dialog().getByText('英文原文已更新，当前中文版需要重新核对。', { exact: true }).waitFor();
  assert((await main().innerText()).includes('提交前审查改动'), 'Stale translation preserved');
  await page.unroute('**/api/invoke/get_skill_translation', staleRead);
  await dialog().getByRole('button', { name: '重新读取中文版', exact: true }).click();
  await wait(async () => await dialog().getByRole('button', { name: '更新中文版', exact: true }).isEnabled());
  checks.push('过期提示明确且保留旧译文');
  await dialog().getByRole('button', { name: '更新中文版', exact: true }).click();
  const editor = dialog().getByRole('textbox', { name: '中文 Markdown 内容', exact: true });
  await editor.fill(current.content + '\n\n用户草稿');
  const external = await invoke('set_skill_translation', { skillId: skill.id, content: current.content + '\n\n其他窗口已保存', sourceHash: current.source_hash, expectedRevision: current.revision });
  await dialog().getByRole('button', { name: '保存中文版', exact: true }).click();
  await dialog().getByText('中文版已被其他窗口修改，请重新读取后合并内容', { exact: true }).waitFor();
  assert((await editor.inputValue()).endsWith('用户草稿'), 'Conflict preserves draft');
  const reread = await invoke('get_skill_translation', { skillId: skill.id });
  assert(reread.content.endsWith('其他窗口已保存'), 'Conflict preserves external saved translation');
  await invoke('set_skill_translation', { skillId: skill.id, content: current.content, sourceHash: external.source_hash, expectedRevision: external.revision });
  await dialog().getByRole('button', { name: '取消编辑', exact: true }).click();
  await dialog().getByRole('button', { name: '重新读取中文版', exact: true }).click();
  checks.push('真实并发冲突保留草稿及另一窗口已保存译文');
  await dialog().getByRole('button', { name: '来源与差异', exact: true }).click();
  await dialog().getByRole('button', { name: '文档', exact: true }).click();
  await wait(async () => (await main().innerText()).includes('提交前审查改动'));
  checks.push('来源与差异往返不影响译文阅读');
  assert(errors.length === 0, 'No uncaught browser errors: ' + errors.join('; '));
  checks.push('浏览器无未捕获运行异常');
  page.off('pageerror', onError);
  return { passed: checks.length, checks, errors };
}
